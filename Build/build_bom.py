#!/usr/bin/env python3
"""Material cost of one WormStation V7 unit.

bom.csv is the only file edited by hand. This script converts every line to
EUR and regenerates:

    list_of_material.md   review view / replication BOM
    bom_summary.tex       thesis table, one row per subsystem
    bom_full.tex          thesis appendix, every line (longtable)

Usage:  python3 build_bom.py
"""
import csv
from collections import OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
CSV_PATH = HERE / "bom.csv"

# ECB euro reference rates of FX_DATE: 1 EUR = 0.9461 CHF = 1.1355 USD.
FX_DATE = "2026-09-29"
FX_TO_EUR = {"EUR": 1.0, "CHF": 1 / 0.9461, "USD": 1 / 1.1355}

# Main components per subsystem, for the summary table.
SUBSYSTEM_BLURB = {
    "Computing & network": "4 Raspberry Pi 4B, microSD cards, Ethernet switch, fans",
    "Imaging": "4 Raspberry Pi HQ cameras, 25 mm lenses",
    "Illumination PCB": "Assembled PCB (3 LP5860T, FT232H), 273 LEDs (IR, orange, blue)",
    "Power & distribution": "Mean Well UHP-200A-5, power-input and distribution PCBs, cabling",
    "Structure (3D-printed PETG)": "Frame, camera plates, microwell holder, LED bars, leg covers",
    "Mechanical hardware": "Threaded rods, nuts, screws",
}

CONVENTIONS = [
    "Materials for one unit only; prices exclude VAT and shipping.",
    "Labour, 3D-printer time, soldering jigs, NAS, workstation, incubator, "
    "consumables (microplates) and a standard IEC C13 power cord are not included.",
    "The 3 mm indicator LED and resistor on the bottom PCB are not included "
    "(no invoice; under 0.50 CHF).",
    "Items sold in minimum quantities (PCBs, SMD parts) are counted per unit, "
    "i.e. order cost divided by the number of boards.",
    "3D-printed parts are costed as sliced filament mass times the price per kg.",
]

SOURCE_LETTER = {"invoice": "I", "list": "L", "estimate": "E"}


def load_rows():
    rows = []
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if not r["subsystem"] or r["subsystem"].startswith("#"):
                continue
            r = {k: (v or "").strip() for k, v in r.items()}
            r["unit"] = r["unit"] or "pcs"
            missing = [n for n, k in (("qty", "qty"), ("price", "unit_price"),
                                      ("currency", "currency")) if not r[k]]
            if r["currency"] and r["currency"] not in FX_TO_EUR:
                raise SystemExit(f"Unknown currency {r['currency']!r} for {r['item']!r}; "
                                 f"add it to FX_TO_EUR.")
            if r["unit_price"] and r["source"] not in SOURCE_LETTER:
                raise SystemExit(f"Source of {r['item']!r} must be one of "
                                 f"{', '.join(SOURCE_LETTER)}, got {r['source']!r}.")
            r["missing"] = missing
            r["eur"] = (None if missing else
                        float(r["qty"]) * float(r["unit_price"]) * FX_TO_EUR[r["currency"]])
            rows.append(r)
    return rows


def by_subsystem(rows):
    groups = OrderedDict()
    for r in rows:
        groups.setdefault(r["subsystem"], []).append(r)
    return groups


def subtotal(rows):
    return sum(r["eur"] for r in rows if r["eur"] is not None)


def fmt_qty(r):
    q = r["qty"]
    if not q:
        return "?"
    q = f"{float(q):g}"
    return q if r["unit"] == "pcs" else f"{q} {r['unit']}"


def fmt_unit_price(r):
    if not r["unit_price"]:
        return "?"
    per = "" if r["unit"] == "pcs" else f"/{r['unit']}"
    p = float(r["unit_price"])
    # Fasteners and LEDs cost fractions of a cent; keep their significant digits.
    digits = 2 if p >= 1 else 3 if p >= 0.1 else 4
    return f"{p:.{digits}f} {r['currency']}{per}"


def fmt_eur(x, digits=2):
    return "?" if x is None else f"{x:,.{digits}f}".replace(",", " ")


def fx_sentence():
    others = " = ".join(f"{1 / v:.4f} {c}" for c, v in FX_TO_EUR.items() if c != "EUR")
    return f"ECB reference rates of {FX_DATE} (1 EUR = {others})"


# --- Markdown -----------------------------------------------------------------

def md_cell(s):
    return s.replace("|", "\\|")


def write_md(rows, groups):
    total = subtotal(rows)
    missing = [r for r in rows if r["missing"]]
    out = ["# WormStation V7: list of material", "",
           "<!-- Generated by build_bom.py from bom.csv. Edit bom.csv, not this file. -->", "",
           "Cost of the materials for **one** WormStation V7 unit (four cameras), in EUR.", ""]
    if missing:
        out += [f"**Total so far: {fmt_eur(total)} EUR**. "
                f"⚠ {len(missing)} of {len(rows)} lines are not priced yet "
                f"(see [Missing](#missing)).", ""]
    else:
        out += [f"**Total: {fmt_eur(total)} EUR**", ""]

    out += ["| Subsystem | Cost (EUR) | Unpriced lines |", "|---|--:|--:|"]
    for name, rs in groups.items():
        n = sum(1 for r in rs if r["missing"])
        out.append(f"| [{name}](#{anchor(name)}) | {fmt_eur(subtotal(rs))} | {n or ''} |")
    out += [f"| **Total** | **{fmt_eur(total)}** | {len(missing) or ''} |", ""]

    out += ["**Conventions**", ""] + [f"- {c}" for c in CONVENTIONS]
    out += [f"- Converted to EUR at {fx_sentence()}.",
            "- Source: *invoice* = price actually paid; *list* = public price on the "
            "given date; *estimate* = no quote found.", ""]

    for name, rs in groups.items():
        out += [f"## {name}", "",
                "| Item | Manufacturer | Part number | Qty | Unit price | Cost (EUR) | Source | Notes |",
                "|---|---|---|--:|--:|--:|---|---|"]
        for r in rs:
            src = f"{r['source']} {r['source_date']}".strip()
            if src and r["url"]:
                src = f"[{src}]({r['url']})"
            out.append("| " + " | ".join(md_cell(c) for c in (
                r["item"], r["manufacturer"], r["part_number"], fmt_qty(r),
                fmt_unit_price(r), fmt_eur(r["eur"]), src, r["notes"])) + " |")
        out += [f"| **Subtotal** | | | | | **{fmt_eur(subtotal(rs))}** | | |", ""]

    out += ['<a id="missing"></a>', "## Missing", ""]
    if missing:
        out += [f"- **{r['subsystem']}**: {r['item']}: {', '.join(r['missing'])}"
                + (f" ({r['notes']})" if r["notes"] else "") for r in missing]
    else:
        out.append("Every line is priced.")
    out.append("")
    (HERE / "list_of_material.md").write_text("\n".join(out), encoding="utf-8")


def anchor(name):
    keep = "".join(ch for ch in name.lower() if ch.isalnum() or ch in " -")
    return keep.replace(" ", "-")


# --- LaTeX --------------------------------------------------------------------

TEX_CHARS = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
             "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
             "^": r"\textasciicircum{}", "×": r"$\times$", "µ": r"\textmu{}",
             "Ω": r"$\Omega$", "°": r"\textdegree{}", " ": r"\,"}


def tex(s):
    return "".join(TEX_CHARS.get(ch, ch) for ch in s)


def caption_extra(rows):
    missing = [r for r in rows if r["missing"]]
    return (f" \\textbf{{INCOMPLETE: {len(missing)} lines not priced yet.}}"
            if missing else "")


def all_invoiced(rows):
    return all(r["source"] == "invoice" for r in rows)


def conventions_tex(rows):
    return (("All prices are taken from purchase invoices. " if all_invoiced(rows) else "")
            + "Prices exclude VAT and shipping; labour, printer time and tools are not included. "
            + f"Converted to EUR at the {tex(fx_sentence())}.")


def write_tex_summary(rows, groups):
    lines = ["% Generated by build_bom.py from bom.csv. Do not edit by hand.",
             r"\begin{table}[htbp]", r"  \centering",
             r"  \caption{Material cost of one WormStation (Version~7, four cameras), in EUR. "
             + conventions_tex(rows) + " Figures are rounded to the nearest euro."
             + caption_extra(rows) + "}",
             r"  \label{tab:wormstation-cost-summary}",
             r"  \begin{tabular}{@{}p{0.28\textwidth}p{0.50\textwidth}r@{}}",
             r"    \toprule",
             r"    Subsystem & Main components & Cost (EUR) \\",
             r"    \midrule"]
    for name, rs in groups.items():
        lines.append(f"    {tex(name)} & {tex(SUBSYSTEM_BLURB.get(name, ''))} & "
                     f"{tex(fmt_eur(subtotal(rs), 0))} \\\\")
    lines += [r"    \midrule",
              rf"    \textbf{{Total}} & & \textbf{{{tex(fmt_eur(subtotal(rows), 0))}}} \\",
              r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    (HERE / "bom_summary.tex").write_text("\n".join(lines), encoding="utf-8")


def write_tex_full(rows, groups):
    # The source column is only worth its width when sources are mixed.
    src = not all_invoiced(rows)
    ncol = 6 if src else 5
    tail = " & " if src else ""
    head = r"Item & Manufacturer / part & Qty & Unit price & Cost (EUR)" + (" & Src." if src else "") + r" \\"
    colspec = (r"p{0.30\textwidth}p{0.22\textwidth}rrrc" if src
               else r"p{0.34\textwidth}p{0.26\textwidth}rrr")
    lines = ["% Generated by build_bom.py from bom.csv. Do not edit by hand.",
             rf"\begin{{longtable}}{{@{{}}{colspec}@{{}}}}",
             r"  \caption{Full bill of materials of one WormStation (Version~7), in EUR. "
             + conventions_tex(rows)
             + (" Src.: I = invoice, L = list price, E = estimate." if src else "")
             + caption_extra(rows) + "}",
             r"  \label{tab:wormstation-cost-full} \\",
             r"  \toprule", "  " + head, r"  \midrule", r"  \endfirsthead",
             r"  \toprule", "  " + head, r"  \midrule", r"  \endhead",
             r"  \bottomrule", r"  \endfoot"]
    for name, rs in groups.items():
        lines.append(rf"  \multicolumn{{{ncol}}}{{@{{}}l}}{{\textit{{{tex(name)}}}}} \\")
        for r in rs:
            part = " ".join(p for p in (r["manufacturer"], r["part_number"]) if p)
            cells = [tex(r["item"]), tex(part), tex(fmt_qty(r)), tex(fmt_unit_price(r)),
                     tex(fmt_eur(r["eur"]))]
            if src:
                cells.append(SOURCE_LETTER.get(r["source"], ""))
            lines.append("  " + " & ".join(cells) + r" \\")
        lines += [rf"  \multicolumn{{4}}{{@{{}}r}}{{Subtotal}} & "
                  rf"{tex(fmt_eur(subtotal(rs)))}{tail}\\", r"  \addlinespace"]
    lines += [r"  \midrule",
              rf"  \multicolumn{{4}}{{@{{}}l}}{{\textbf{{Total}}}} & "
              rf"\textbf{{{tex(fmt_eur(subtotal(rows)))}}}{tail}\\",
              r"\end{longtable}", ""]
    (HERE / "bom_full.tex").write_text("\n".join(lines), encoding="utf-8")


def main():
    rows = load_rows()
    groups = by_subsystem(rows)
    write_md(rows, groups)
    write_tex_summary(rows, groups)
    write_tex_full(rows, groups)

    width = max(len(n) for n in groups)
    for name, rs in groups.items():
        n = sum(1 for r in rs if r["missing"])
        print(f"{name:<{width}}  {subtotal(rs):>10.2f} EUR" + (f"   ({n} unpriced)" if n else ""))
    missing = sum(1 for r in rows if r["missing"])
    print(f"{'TOTAL':<{width}}  {subtotal(rows):>10.2f} EUR"
          + (f"   ⚠ {missing}/{len(rows)} lines unpriced" if missing else ""))


if __name__ == "__main__":
    main()
